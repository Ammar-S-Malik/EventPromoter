"""Generate src/metrics.js: per-glyph advance widths (em units) for the brand fonts.
Run once; the output is committed so the runtime has zero font dependencies."""
import json, sys
from fontTools.ttLib import TTFont

G = "/usr/share/fonts/truetype/google-fonts/"
I = "/usr/share/fonts/opentype/inter/"
FONTS = {
    "poppins-700": G + "Poppins-Bold.ttf",
    "poppins-500": G + "Poppins-Medium.ttf",
    "poppins-400": G + "Poppins-Regular.ttf",
    "inter-700": I + "Inter-Bold.otf",
    "inter-400": I + "Inter-Regular.otf",
}
EXTRA = [0x2019, 0x2013, 0x2014, 0x2022, 0xB7, 0xE9, 0xE8, 0xE0, 0xE7, 0x201C, 0x201D, 0xA0, 0x2192]
out = {}
for key, path in FONTS.items():
    f = TTFont(path)
    cmap, hmtx, upm = f.getBestCmap(), f["hmtx"], f["head"].unitsPerEm
    widths = {}
    for cp in list(range(32, 127)) + EXTRA:
        g = cmap.get(cp)
        if g:
            widths[chr(cp)] = round(hmtx[g][0] / upm, 4)
    out[key] = {"fallback": widths["n"], "widths": widths}
with open("src/metrics.js", "w") as fh:
    fh.write("// GENERATED by tools/gen-metrics.py - do not edit\nexport default ")
    json.dump(out, fh, ensure_ascii=False)
    fh.write(";\n")
print("ok", {k: len(v["widths"]) for k, v in out.items()})
